#!/usr/bin/env bash
# Amalgamate the pinned botkit.hpp + this entry into ONE source file.
# CodeCup requires a single source file; estate code reuse happens here,
# at artifact-build time. Output: submission/tumbleweed.cpp
set -euo pipefail
cd "$(dirname "$0")/.."

PIN="$(cat BOTKIT_PIN)"

mkdir -p submission
{
    echo "// WyattAu/tumbleweed — CodeCup 2027 submission artifact"
    echo "// Amalgamated from WyattAu/bot-kit@${PIN} cpp/botkit/botkit.hpp"
    echo "// Generated by scripts/amalgamate.sh — source of truth: tumbleweed.cpp"
    echo
    cat vendor/botkit.hpp
    echo
    grep -vE '^(#include "vendor/botkit.hpp"|#pragma once)$' tumbleweed.cpp
} > submission/tumbleweed.cpp

# The artifact must compile standalone — same gate as the judge (single TU).
g++ -std=c++23 -O2 -Wall -Wextra -Wpedantic -o /tmp/tw-artifact-check submission/tumbleweed.cpp

echo "submission/tumbleweed.cpp ready ($(wc -c < submission/tumbleweed.cpp) bytes, bot-kit@${PIN})"
